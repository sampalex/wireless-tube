import { Page, Section, Metrics, Segmented, Toggle, Table, Status, Text, useState } from "grok/canvas";

type Item = { t: string; u: string; k: string; s: string; tp: string; n?: number; nt?: number; f?: string; d?: string };
type Topic = { id: string; label: string; count: number; videos: number; new: number; new_today: number };
type Src = { name: string; status: string; fetched: number; new: number };
type Data = {
  generated_at_pt: string; badge_days: number;
  counts: { total: number; videos: number; seed: number; new_7d: number; new_today: number };
  topics: Topic[]; items: Item[];
  last_run: { run_id: number; started_at_pt: string; sources: Src[] } | null;
};

// Generated by /workspace/wireless-tube/wtube/build.py from wireless_tube.db. Do not hand-edit; rerun run_daily.sh.
const DATA: Data = __DATA__;

const topicLabel: Record<string, string> = Object.fromEntries(DATA.topics.map((t) => [t.id, t.label]));

function TitleCell({ it }: { it: Item }) {
  return (
    <span>
      <a href={it.u} target="_blank" rel="noreferrer">{it.t}</a>
      {it.d ? <span> · <a href={it.d} target="_blank" rel="noreferrer">discussion</a></span> : null}
    </span>
  );
}

function badge(it: Item) {
  return it.n ? <Status tone="accent">{"New · " + (it.f ?? "")}</Status> : "";
}

function rows(items: Item[], withTopic: boolean) {
  return items.map((it) => withTopic
    ? [<TitleCell it={it} />, topicLabel[it.tp] ?? it.tp, it.k, it.s, badge(it)]
    : [<TitleCell it={it} />, it.k, it.s, badge(it)]);
}

export default function App() {
  const [topic, setTopic] = useState<string>("all");
  const [videosOnly, setVideosOnly] = useState<boolean>(false);
  const today = DATA.items.filter((i) => i.nt);
  const week = DATA.items.filter((i) => i.n && !i.nt);
  const shown = DATA.items.filter((i) => (topic === "all" || i.tp === topic) && (!videosOnly || i.k === "video"));
  const options = [{ value: "all", label: "All", count: DATA.counts.total },
    ...DATA.topics.map((t) => ({ value: t.id, label: t.label, count: t.count }))];
  const c = DATA.counts;
  return (
    <Page width="wide" title="Wireless Tube"
      summary={`A wireless-only video and reading feed for 5G, 6G, Wi-Fi, MAC/PHY, signal processing, beamforming and massive MIMO. Videos come first in each topic. Updated ${DATA.generated_at_pt}.`}>
      <Text>{`${c.new_today} items were first seen in the last 24 hours, out of ${c.total} tracked. Items found by the daily checker carry a New badge for ${DATA.badge_days} days.`}</Text>
      <Metrics metrics={[
        { value: String(c.total), label: "Items", detail: `${c.seed} seed + ${c.total - c.seed} found by the checker` },
        { value: String(c.videos), label: "Videos" },
        { value: String(c.new_today), label: "New today", detail: "first seen in the last 24 h" },
        { value: String(c.new_7d), label: `New in ${DATA.badge_days} days`, detail: "carry a New badge" },
      ]} />

      {today.length ? (
        <Section heading={`New today (${today.length})`} id="new-today">
          <Table columns={["Title", "Topic", "Type", "Source", "Badge"]} rows={rows(today, true)} />
        </Section>
      ) : null}
      {week.length ? (
        <Section heading={`Earlier this week (${week.length})`} id="new-week">
          <Table columns={["Title", "Topic", "Type", "Source", "Badge"]} rows={rows(week, true)} />
        </Section>
      ) : null}

      <Section heading="Browse by topic" id="topics" caption="Videos first within each topic, then papers, reports and pages.">
        <Segmented options={options} value={topic} onChange={setTopic} />
        <Toggle label="Videos only" value={videosOnly} onChange={setVideosOnly} />
        <Table columns={topic === "all" ? ["Title", "Topic", "Type", "Source", "Badge"] : ["Title", "Type", "Source", "Badge"]}
          rows={rows(shown, topic === "all")} />
      </Section>

      {DATA.last_run ? (
        <Section heading="Last checker run" collapsible defaultOpen={false}>
          <Table columns={["Source", "Status", "Fetched", "New"]}
            rows={DATA.last_run.sources.map((s) => [s.name, s.status === "failed" ? { text: s.status, tone: "danger" as const } : s.status, String(s.fetched), String(s.new)])} />
          <Text>{`Run #${DATA.last_run.run_id}, started ${DATA.last_run.started_at_pt}. A New badge lasts ${DATA.badge_days} days from when the checker first saw the item. Seed items never carry one.`}</Text>
        </Section>
      ) : null}
    </Page>
  );
}
